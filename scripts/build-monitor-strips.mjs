// Build the Live Monitor strip bank: 50 strips in each of six categories
// (sinus, atrial, junctional, ventricular, AV blocks, paced) = 300 strips.
//
// A strip is a rhythm plus a fixed seed. The site's own ECG engine turns that
// into the same waveform every time, so this script runs the engine once per
// strip to record what that particular strip shows (its rate, PR interval,
// QRS width and conduction notes) and picks four answer choices.
//
// Output: site/js/monitor-strips.js  (window.ECGMonitorBank)
// Run:    node scripts/build-monitor-strips.mjs   (part of `npm run build`)

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {}, Math, console };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ['site/js/ecg-engine.js', 'site/js/content.js']) vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f });
const E = ctx.ECGEngine, R = ctx.ECGContent.RHYTHMS;

export const SECONDS = 30; // length of signal the monitor loops
export const GEN_OPTS = { vary: true };

// [category, title, course unit, rhythms with how many strips each]
const CATS = [
	['sinus', 'Sinus rhythms', 4, { nsr: 10, sbrady: 10, stach: 10, sarrhythmia: 10, sarrest: 10 }],
	['atrial', 'Atrial rhythms', 5, { pac: 9, wap: 9, mat: 8, flutter: 8, afib: 8, svt: 8 }],
	['junctional', 'Junctional rhythms', 6, { pjc: 13, junctEscape: 13, accelJunct: 12, junctTach: 12 }],
	['ventricular', 'Ventricular rhythms', 7, { pvc: 6, bigeminy: 6, multifocal: 6, idio: 6, aivr: 6, vt: 5, torsades: 5, vf: 5, asystole: 5 }],
	['blocks', 'AV blocks', 8, { firstDeg: 10, wenck: 10, mobitz2: 10, twoToOne: 10, chb: 10 }],
	['paced', 'Pacemaker rhythms', 9, { vpaced: 17, avpaced: 17, failCapture: 16 }]
];
// extra look-alike choices for categories with fewer than four rhythms
const EXTRA = { paced: ['idio', 'aivr', 'chb'] };

for (const [, , , mix] of CATS) for (const r of Object.keys(mix)) if (!R[r] || !E.generators[r]) throw new Error('Unknown rhythm ' + r);

const rng = E.mulberry32(20261116);
function shuffle(a) { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

// Spread the rhythms through the 50 so the same one rarely comes twice in a row.
function interleave(mix) {
	let out;
	for (let tries = 0; tries < 200; tries++) {
		out = shuffle(Object.entries(mix).flatMap(([r, n]) => Array(n).fill(r)));
		let repeats = 0;
		for (let i = 1; i < out.length; i++) if (out[i] === out[i - 1]) repeats++;
		if (repeats <= 2) break;
	}
	return out;
}

const r1 = (x) => Math.round(x);
function describe(r, sig) {
	const m = sig.meta || {}, s = {};
	if (r === 'asystole') s.rate = 'None';
	else if (r === 'vf') s.rate = 'None: no QRS complexes to count';
	else if (r === 'torsades') s.rate = '≈ ' + r1(m.rate) + '/min (too chaotic to count precisely)';
	else if (['flutter', 'wenck', 'mobitz2', 'twoToOne', 'chb'].includes(r)) s.rate = 'Ventricular ' + sig.measuredRate + '/min';
	else if (r === 'failCapture') s.rate = 'Ventricular ' + sig.measuredRate + '/min (only the captured beats)';
	else s.rate = sig.measuredRate + '/min';
	if (m.pr) s.pr = m.pr.toFixed(2) + ' s';
	if (m.wide === true) s.wide = 1;
	if (m.wide === false) s.wide = 0;
	if (m.note) s.note = m.note;
	return s;
}

const cats = CATS.map(([id, title, unit, mix], ci) => {
	const rhythms = Object.keys(mix);
	const order = interleave(mix);
	const strips = order.map((r, i) => {
		const seed = 100000 + ci * 1000 + i * 17 + 3;
		const sig = E.generate(r, seed, SECONDS, GEN_OPTS);
		const pool = rhythms.filter((x) => x !== r).concat((EXTRA[id] || []).filter((x) => x !== r));
		const opts = shuffle([r].concat(shuffle(pool).slice(0, 3)));
		return Object.assign({ n: i + 1, id: id + '-' + String(i + 1).padStart(2, '0'), r, seed, opts }, describe(r, sig));
	});
	return { id, title, unit, rhythms, strips };
});

const total = cats.reduce((a, c) => a + c.strips.length, 0);
const bank = { seconds: SECONDS, gen: GEN_OPTS, cats };
const out = '/* Generated by scripts/build-monitor-strips.mjs: do not edit by hand. */\nwindow.ECGMonitorBank = ' + JSON.stringify(bank) + ';\n';
fs.writeFileSync(path.join(ROOT, 'site/js/monitor-strips.js'), out);
console.log(`Built the Live Monitor bank: ${total} strips in ${cats.length} categories (${(out.length / 1024).toFixed(0)} KB).`);
