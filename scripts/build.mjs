#!/usr/bin/env node
// Build the course for deployment.
//
// src/course.js holds the whole course. This splits it in two:
//   site/js/course-preview.js              public: Unit 1 in full, and only the
//                                          titles of the other units' lessons
//   netlify/data/course-full.json  every unit, served only to
//                                          enrolled students by course-content
// so the paid lessons are never part of the public site.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FREE_UNITS = 1;

const sandbox = {};
sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'src/course.js'), 'utf8'), sandbox, { filename: 'src/course.js' });
const { UNITS, PASS, EXAM } = sandbox.ECGCourse;

const full = JSON.parse(JSON.stringify({ UNITS, PASS, EXAM }));
const version = crypto.createHash('sha256').update(JSON.stringify(full)).digest('hex').slice(0, 12);
full.version = version;

const preview = {
	version,
	PASS,
	EXAM,
	UNITS: full.UNITS.map((u, i) =>
		i < FREE_UNITS
			? u
			: {
					...u,
					locked: true,
					bank: [],
					lessons: u.lessons.map((l) => ({ id: l.id, title: l.title, min: l.min, practice: !!l.practice, blocks: [] }))
				}
	)
};

const previewJs = `/* GENERATED by scripts/build.mjs from src/course.js. Do not edit. */
(function (g) {
  'use strict';
  var C = ${JSON.stringify(preview)};
  C.unitById = function (id) { return C.UNITS.filter(function (u) { return u.id === id; })[0]; };
  g.ECGCourse = C;
})(window);
`;

fs.writeFileSync(path.join(ROOT, 'site/js/course-preview.js'), previewJs);
fs.mkdirSync(path.join(ROOT, 'netlify/data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'netlify/data/course-full.json'), JSON.stringify(full));
const lessons = full.UNITS.reduce((n, u) => n + u.lessons.length, 0);
console.log(
	`Built course ${version}: ${full.UNITS.length} units, ${lessons} lessons; ${FREE_UNITS} unit free in site/js/course-preview.js, all in netlify/data/course-full.json.`
);
